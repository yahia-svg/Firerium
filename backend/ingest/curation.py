"""Project-team curation layer on top of the raw NASA PSI records.

PSI gives us free text (objective, approach, ...) and run tables, but not tidy
fields such as "fuel state" or "which fire-safety pillar". This file adds those.

Rules we hold ourselves to:
  * Nothing here replaces PSI text; the verbatim record is always shown too.
  * Every numeric condition in `stated` carries a `quote` that must appear in the
    PSI record. build_db.py checks this and fails the build if a quote is missing,
    so a typo or an invented value cannot reach the website.
  * Numeric ranges taken from run tables are NOT written here; build_db.py
    computes them from the CSV files (see TABLE_SPECS).
  * `summary` and `safety_note` are our own plain-language wording and are
    labelled as such in the UI.

`directness` (how directly an investigation speaks to spacecraft fire safety):
  3 = named in the NASA challenge text as a prevention / detection / suppression study
  2 = given a specific fire-safety link in the challenge text, or filed by PSI
      under a spacecraft-fire-safety sub-area
  1 = other combustion science ("still relevant ... just not as strongly or directly")
This is a project choice, not a NASA rating.
"""

